import unittest

from convert_mysql_dump import mysql_literal, parse_dump, render_postgresql, split_sql


SCHEMA = """CREATE TABLE `sample` (
  `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `note` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `is_active` int(11) NOT NULL DEFAULT '1',
  PRIMARY KEY (`id`) USING BTREE
) ENGINE=InnoDB AUTO_INCREMENT=19 DEFAULT CHARSET=utf8mb4;"""


class ConverterTest(unittest.TestCase):
    def test_preserves_quotes_unicode_backslashes_and_statement_delimiters(self):
        dump = SCHEMA + r"INSERT INTO `sample` VALUES (2,'O\'Brien; (x), \\path; 日本語',1),(3,'a''b',0);"
        tables = parse_dump(dump)
        self.assertEqual(tables['sample']['rows'], [[2, "O'Brien; (x), \\path; 日本語", 1], [3, "a'b", 0]])
        sql = render_postgresql(tables, 'source-hash')
        self.assertIn("O''Brien; (x), \\path; 日本語", sql)
        self.assertIn('standard_conforming_strings = on', sql)

    def test_null_and_empty_string_are_distinct(self):
        tables = parse_dump(SCHEMA + "INSERT INTO `sample` VALUES (1,NULL,1),(2,'',1);")
        self.assertIsNone(tables['sample']['rows'][0][1])
        self.assertEqual(tables['sample']['rows'][1][1], '')

    def test_preserves_deleted_id_gaps_in_auto_increment_counter(self):
        tables = parse_dump(SCHEMA + "INSERT INTO `sample` VALUES (2,'value',1);")
        sql = render_postgresql(tables, 'hash')
        self.assertIn('GENERATED BY DEFAULT AS IDENTITY', sql)
        self.assertIn(", 'id'), 19, false)", sql)
        self.assertNotIn('DROP TABLE', sql)
        self.assertNotIn('TRUNCATE', sql.split('BEGIN;')[1])
        self.assertTrue(sql.rstrip().endswith('COMMIT;'))

    def test_rejects_unsupported_values_instead_of_silently_changing_data(self):
        with self.assertRaises(ValueError):
            parse_dump(SCHEMA + "INSERT INTO `sample` VALUES (1,NOW(),1);")
        with self.assertRaises(ValueError):
            mysql_literal(r"'null\0byte'")
        with self.assertRaises(ValueError):
            parse_dump(SCHEMA + "INSERT INTO `sample` VALUES (18446744073709551615,'too large',1);")

    def test_rejects_unknown_columns_statements_and_invalid_schema_names(self):
        with self.assertRaises(ValueError):
            parse_dump(SCHEMA + "INSERT INTO `sample` VALUES (1,'missing column');")
        with self.assertRaises(ValueError):
            parse_dump(SCHEMA + 'DELETE FROM `sample`;')
        with self.assertRaises(ValueError):
            render_postgresql(parse_dump(SCHEMA), 'hash', 'public; DROP DATABASE example')

    def test_mysql_comment_removal_does_not_change_literals(self):
        dump = '-- header\n/*!40101 SET NAMES utf8 */;\n' + SCHEMA + "INSERT INTO `sample` VALUES (1,'-- /*literal*/ #keep',1);"
        self.assertEqual(parse_dump(dump)['sample']['rows'][0][1], '-- /*literal*/ #keep')
        self.assertEqual(split_sql("'a;b';'c';"), ["'a;b'", "'c'"])


if __name__ == '__main__':
    unittest.main()
